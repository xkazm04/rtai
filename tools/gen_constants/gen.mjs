#!/usr/bin/env node
// NAT-08: one source (sim_constants.json) -> the GDScript and C++ constant files.
//   node tools/gen_constants/gen.mjs          write both outputs
//   node tools/gen_constants/gen.mjs --check  fail if a committed output drifted (lint runs this)
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT, rel } from '../lib/repo.mjs';

const SOURCE = join(ROOT, 'tools', 'gen_constants', 'sim_constants.json');
export const GD_OUT = join(ROOT, 'project', 'features', 'city', 'sim', 'sim_constants.gd');
export const H_OUT = join(ROOT, 'native', 'sim_core', 'src', 'sim_constants.h');

/** NAT-07: a float constant must be exact in binary, or GDScript and MSVC may round it apart. */
const exactFloat = (v) => Number.isFinite(v) && Number.isInteger(v * 1024);

function load() {
  const text = readFileSync(SOURCE, 'utf8');
  const doc = JSON.parse(text);
  const errors = [];
  const seen = new Set();
  for (const g of doc.groups) {
    for (const c of g.constants) {
      if (seen.has(c.name)) errors.push(`${c.name}: duplicate`);
      seen.add(c.name);
      if (!/^[A-Z][A-Z0-9_]*$/.test(c.name)) errors.push(`${c.name}: not UPPER_SNAKE`);
      if (c.type === 'int' && !Number.isSafeInteger(c.value)) errors.push(`${c.name}: not an int`);
      if (c.type === 'float' && !exactFloat(c.value)) errors.push(`${c.name}: float not exact (NAT-07)`);
      if (!['int', 'float'].includes(c.type)) errors.push(`${c.name}: type ${c.type}`);
    }
  }
  const sha = createHash('sha256').update(text).digest('hex');
  return { doc, errors, sha };
}

const fmt = (c) => (c.type === 'float' ? (Number.isInteger(c.value) ? `${c.value}.0` : `${c.value}`) : `${c.value}`);

export function gdText(doc, sha) {
  const out = [
    '# DO NOT EDIT. Generated by tools/gen_constants/gen.mjs from tools/gen_constants/sim_constants.json.',
    `# source-sha256: ${sha}`,
    'class_name SimConst',
    'extends RefCounted',
    '## Constants shared with the native sim (NAT-08): native/sim_core/src/sim_constants.h.',
  ];
  for (const g of doc.groups) {
    out.push('', `# ${g.name}: ${g.doc}`);
    for (const c of g.constants) out.push(`const ${c.name}: ${c.type} = ${fmt(c)}  # ${c.doc}`);
  }
  return `${out.join('\n')}\n`;
}

export function hText(doc, sha) {
  const out = [
    '// DO NOT EDIT. Generated by tools/gen_constants/gen.mjs from tools/gen_constants/sim_constants.json.',
    `// source-sha256: ${sha}`,
    '// Constants shared with the GDScript reference sim (NAT-08): project/features/city/sim/sim_constants.gd.',
    '#pragma once',
    '',
    'namespace gtai::sim {',
  ];
  for (const g of doc.groups) {
    out.push('', `// ${g.name}: ${g.doc}`);
    for (const c of g.constants) {
      const t = c.type === 'float' ? 'double' : 'int';
      out.push(`inline constexpr ${t} ${c.name} = ${fmt(c)};  // ${c.doc}`);
    }
  }
  out.push('', '}  // namespace gtai::sim');
  return `${out.join('\n')}\n`;
}

export function check() {
  const { doc, errors, sha } = load();
  const issues = [...errors];
  for (const [path, text] of [[GD_OUT, gdText(doc, sha)], [H_OUT, hText(doc, sha)]]) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== text) {
      issues.push(`${rel(path)} drifted: run node tools/gen_constants/gen.mjs`);
    }
  }
  return { name: 'sim-constants', ok: !issues.length, issues };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.includes('--check')) {
    const res = check();
    for (const i of res.issues) console.error(i);
    process.exit(res.ok ? 0 : 1);
  }
  const { doc, errors, sha } = load();
  if (errors.length) {
    for (const e of errors) console.error(e);
    process.exit(1);
  }
  for (const [path, text] of [[GD_OUT, gdText(doc, sha)], [H_OUT, hText(doc, sha)]]) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text, 'utf8');
    console.log(`wrote ${rel(path)}`);
  }
}
