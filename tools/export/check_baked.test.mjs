import { after, test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { checkBaked } from './check_baked.mjs';

const made = [];
after(() => { for (const d of made) fs.rmSync(d, { recursive: true, force: true }); });
const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');
function tree(chunks, listed = chunks) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'baked-'));
  made.push(root);
  const city = path.join(root, 'city');
  fs.mkdirSync(city);
  for (const [n, b] of Object.entries(chunks)) fs.writeFileSync(path.join(city, n), b);
  const lines = ['# DO NOT EDIT. Generated by res://dev/bake_city.gd (district_01, generator v14, GTCH v1).', ...Object.entries(listed).map(([n, b]) => `${sha(b)}  ${n}`)];
  const list = path.join(root, 'city_chunks.sha256');
  fs.writeFileSync(list, `${lines.join('\n')}\n`);
  return { list, city };
}

test('every listed chunk present and matching is ok', () => {
  const r = checkBaked(tree({ 'c_00_00.bin': 'a', 'c_00_01.bin': 'b' }));
  assert.equal(r.ok, true);
  assert.equal(r.expected, 2);
  assert.deepEqual(r.missing, []);
  assert.deepEqual(r.mismatched, []);
});

test('a tree that never baked reports every chunk missing', () => {
  const t = tree({ 'c_00_00.bin': 'a' });
  fs.rmSync(t.city, { recursive: true });
  const r = checkBaked(t);
  assert.equal(r.ok, false);
  assert.deepEqual(r.missing, ['c_00_00.bin']);
});

test('a stale chunk is a mismatch and named', () => {
  const r = checkBaked(tree({ 'c_00_00.bin': 'new' }, { 'c_00_00.bin': 'old' }));
  assert.equal(r.ok, false);
  assert.deepEqual(r.mismatched, ['c_00_00.bin']);
});

test('the comment line is not a chunk', () => {
  assert.equal(checkBaked(tree({ 'c_00_00.bin': 'a' })).expected, 1);
});

test('an empty list is not ok: nothing was checked', () => {
  assert.equal(checkBaked(tree({})).ok, false);
});

test('a missing list file is not ok and does not throw', () => {
  const t = tree({ 'c_00_00.bin': 'a' });
  fs.rmSync(t.list);
  assert.equal(checkBaked(t).ok, false);
});

test('CRLF list files parse the same', () => {
  const t = tree({ 'c_00_00.bin': 'a' });
  fs.writeFileSync(t.list, fs.readFileSync(t.list, 'utf8').replaceAll('\n', '\r\n'));
  assert.equal(checkBaked(t).ok, true);
});
