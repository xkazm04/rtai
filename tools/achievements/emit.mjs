// ACH-05 outputs. Committed: ach_ids.gd + achievements_runtime.json (drift-checked by --check).
// Build-only (git-ignored): build/steam/achievements/ checklists. CSVs and icons are TODO.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { canonicalJson } from '../lib/canonical_json.mjs';
import { ROOT } from '../lib/repo.mjs';

export const IDS_PATH = join(ROOT, 'project', 'core', 'platform', 'achievements', 'ach_ids.gd');
export const RUNTIME_PATH = join(ROOT, 'project', 'data', 'generated', 'achievements_runtime.json');
export const BUILD_DIR = join(ROOT, 'build', 'steam', 'achievements');
const TEMPLATE_DIR = join(ROOT, 'steam', 'achievements', 'templates');
const GENERATOR = 'tools/achievements/gen.mjs';
const SOURCE = 'steam/achievements/achievements.json';

const sourceHash = (doc) => createHash('sha256').update(canonicalJson(doc)).digest('hex');

function constLine(name) {
  const one = `const ${name}: StringName = &"${name}"`;
  return one.length <= 100 ? one : `const ${name}: StringName = (\n\t&"${name}"\n)`;
}

export function achIdsGd(doc) {
  const achIds = doc.achievements.map((a) => a.id);
  const statIds = doc.stats.map((s) => s.id);
  const list = (ids) => (ids.length ? `[\n${ids.map((i) => `\t${i},\n`).join('')}]` : '[]');
  return [
    `# DO NOT EDIT. Generated by ${GENERATOR} from ${SOURCE}.`,
    `# source-sha256: ${sourceHash(doc)}`,
    'class_name AchIds',
    'extends RefCounted',
    '## Achievement and stat ids (ACH-05). Regenerate: node tools/achievements/gen.mjs emit',
    '',
    ...[...achIds, ...statIds].map(constLine),
    '',
    `const ALL_ACHIEVEMENTS: Array[StringName] = ${list(achIds)}`,
    `const ALL_STATS: Array[StringName] = ${list(statIds)}`,
    '',
  ].join('\n');
}

/** Triggers and bindings only, no text (ACH-05). */
export function runtimeJson(doc) {
  return canonicalJson({
    schema: 'gtai.achievements-runtime/1',
    generatedBy: GENERATOR,
    sourceSha256: sourceHash(doc),
    achievements: doc.achievements.map((a) => ({
      id: a.id,
      ...(a.stat ? { stat: a.stat } : {}),
      trigger: a.trigger,
    })),
    stats: doc.stats.map(({ id, type, min, max, default: def }) => ({ id, type, min, max, default: def })),
  });
}

export function buildOnlyFiles(doc) {
  const stats = doc.stats.map((s) => `| ${s.id} | ${s.type} | ${s.min} | ${s.max} | ${s.default} |`);
  const files = {
    'STATS_TO_CREATE.md': [
      '# Stats to create by hand (ACH-12 step 1)', '',
      '| API name | Type | Min | Max | Default |', '|---|---|---|---|---|', ...stats, '',
    ].join('\n'),
    'UPLOAD_CHECKLIST.md': [
      '# Achievements upload checklist (ACH-12, about 5 human minutes)', '',
      '1. Create the stats in STATS_TO_CREATE.md by hand.',
      '2. Run Bulk Import with definitions.csv and localization.csv.',
      '3. Click "Save imported data".', '4. Publish.',
      '5. Enable the Steam Achievements feature.', '',
    ].join('\n'),
  };
  const todo = [];
  for (const csv of ['definitions.csv', 'localization.csv']) {
    if (existsSync(join(TEMPLATE_DIR, csv))) {
      files[csv] = `${readFileSync(join(TEMPLATE_DIR, csv), 'utf8').split('\n')[0]}\n`;
      todo.push(`${csv}: header only; rows TODO`);
    } else {
      todo.push(`${csv}: TODO, needs the partner-site template in steam/achievements/templates/`);
    }
  }
  todo.push('icons/<ID>_ACHIEVED.png + _UNACHIEVED.png: TODO (ACH-06 pipeline)');
  return { files, todo };
}
